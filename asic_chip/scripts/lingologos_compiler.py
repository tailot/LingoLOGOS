# ---------------------------------------------------------------------------
# field arithmetic on GF(2^8)
# ---------------------------------------------------------------------------

def gf_mul(left: int, right: int, poly: int) -> int:
    """Carry-less product of two bytes reduced modulo the field polynomial."""
    result = 0
    operand = left
    for bit in range(8):
        if (right >> bit) & 1:
            result ^= operand << bit
    for bit in range(15, 7, -1):
        if (result >> bit) & 1:
            result ^= poly << (bit - 8)
    return result & 0xFF


def gf_inverse(value: int, poly: int) -> int:
    """Multiplicative inverse by exhaustive search over the 255 nonzero elements."""
    if value == 0:
        raise ValueError("zero has no inverse in GF(2^8)")
    for candidate in range(1, 256):
        if gf_mul(value, candidate, poly) == 1:
            return candidate
    raise ValueError(f"no inverse found for {value:#04x}, polynomial is not a field")


def gf_order(value: int, poly: int) -> int:
    """Multiplicative order of a field element (smallest k > 0 with value^k == 1)."""
    if value == 0:
        raise ValueError("zero has no multiplicative order")
    current = value
    order = 1
    while current != 1:
        current = gf_mul(current, value, poly)
        order += 1
        if order > 255:
            raise ValueError("element order exceeds the group size, polynomial is not a field")
    return order


def gf2_poly_mod(dividend: int, poly: int) -> int:
    """Remainder of two binary polynomials."""
    for bit in range(dividend.bit_length() - 1, poly.bit_length() - 2, -1):
        if (dividend >> bit) & 1:
            dividend ^= poly << (bit - (poly.bit_length() - 1))
    return dividend


def gf2_poly_gcd(first: int, second: int) -> int:
    while second:
        first, second = second, gf2_poly_mod(first, second)
    return first


def gf2_poly_pow_x(power_bits: int, poly: int) -> int:
    """x**(2**power_bits) modulo poly, the Frobenius chain used by the irreducibility test."""
    value = 0x02  # x
    for _ in range(power_bits):
        value = gf2_poly_square_mod(value, poly)
    return value


def gf2_poly_square_mod(value: int, poly: int) -> int:
    """Square of a binary polynomial modulo poly (carry-less squaring)."""
    squared = 0
    for bit in range(value.bit_length()):
        if (value >> bit) & 1:
            squared ^= 1 << (2 * bit)
    return gf2_poly_mod(squared, poly)


def is_irreducible(poly: int) -> bool:
    """
    A degree-d polynomial over GF(2) is irreducible iff it divides x**(2**d) - x and is
    coprime with x**(2**k) - x for every proper divisor k of d. For d = 8 that is k in 1..4.
    """
    degree = poly.bit_length() - 1
    if degree != 8 or poly < 0x100:
        return False
    for k in range(1, 4):
        residue = gf2_poly_pow_x(k, poly) ^ 0x02
        if gf2_poly_gcd(residue, poly) != 1:
            return False
    return (gf2_poly_pow_x(8, poly) ^ 0x02) == 0


