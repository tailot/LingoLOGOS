# H2: GF(2^8) automaton
# ---------------------------------------------------------------------------

def parse_hex(value: object, field: str) -> int:
    if not isinstance(value, str):
        raise ValueError(f"{field} must be a hex string, got {value!r}")
    if not re.fullmatch(r"0[xX][0-9a-fA-F]{1,4}", value):
        raise ValueError(f"{field} is not a 0x hex literal: {value!r}")
    return int(value, 16)


def build_gf_transitions(gf_artifact: Dict[str, object]) -> Dict[str, object]:
    """
    Enumerate the automaton reachable from the initial state using field arithmetic, then
    emit the closed transition table. The compiler never trusts the declared multipliers:
    it checks the polynomial is irreducible and every multiplier is invertible.
    """
    poly = parse_hex(gf_artifact.get("polynomial"), "polynomial")
    if not is_irreducible(poly):
        raise ValueError(f"polynomial {poly:#05x} is not irreducible over GF(2), no field GF(2^8)")
    initial = parse_hex(gf_artifact.get("initial_state"), "initial_state")
    if initial == 0:
        raise ValueError("initial_state 0 is a sink: every transition would leave the automaton dead")
    budget = int(gf_artifact.get("state_budget", 255))

    symbols: List[Dict[str, int]] = []
    for entry in gf_artifact.get("symbols", []):  # type: ignore[union-attr]
        byte = parse_hex(entry.get("byte"), "symbol byte")
        multiplier = parse_hex(entry.get("multiplier"), "symbol multiplier")
        if multiplier == 0:
            raise ValueError(f"symbol {entry.get('name')} has multiplier 0, not invertible")
        inverse = gf_inverse(multiplier, poly)
        symbols.append(
            {
                "byte": byte,
                "multiplier": multiplier,
                "inverse": inverse,
                "order": gf_order(multiplier, poly),
            }
        )
    if not symbols:
        raise ValueError("no symbols declared")
    seen_bytes = {}
    for symbol in symbols:
        if symbol["byte"] in seen_bytes:
            raise ValueError(f"symbol byte {symbol['byte']:#04x} declared twice")
        seen_bytes[symbol["byte"]] = True

    reachable: List[int] = [initial]
    visited = {initial}
    transitions: List[Tuple[int, int, int]] = []
    while reachable:
        state = reachable.pop(0)
        for symbol in symbols:
            nxt = gf_mul(state, symbol["multiplier"], poly)
            transitions.append((state, symbol["byte"], nxt))
            if nxt not in visited:
                visited.add(nxt)
                reachable.append(nxt)
    if len(visited) > budget:
        raise ValueError(
            f"reachable closure is {len(visited)} states, above the declared budget {budget}"
        )
    keys = {(state, symbol) for state, symbol, _ in transitions}
    if len(keys) != len(transitions):
        raise ValueError("duplicate (state, symbol) key in the transition table")
    transitions.sort()

    lines: List[str] = ["  always_comb begin", "    unique case ({current_state, symbol_in})"]
    for state, symbol, nxt in transitions:
        lines.append(f"      16'h{state:02X}{symbol:02X}: next_state = 8'h{nxt:02X};")
    lines.append(f"      default: next_state = 8'h{initial:02X};")
    lines.append("    endcase")
    lines.append("  end")

    return {
        "poly": poly,
        "initial": initial,
        "budget": budget,
        "symbols": symbols,
        "transitions": transitions,
        "state_count": len(visited),
        "symbol_orders": sorted({symbol["order"] for symbol in symbols}),
        "body": "\n".join(lines),
    }


def gf_apply(gf_info: Dict[str, object], state: int, symbol_byte: int) -> int:
    """Reference step of the automaton: multiply by the symbol multiplier, else reset."""
    for symbol in gf_info["symbols"]:  # type: ignore[index]
        if symbol["byte"] == symbol_byte:
            return gf_mul(state, symbol["multiplier"], gf_info["poly"])  # type: ignore[arg-type]
    return int(gf_info["initial"])  # type: ignore[return-value]


# ---------------------------------------------------------------------------
# H3: SMT clause DSL
# ---------------------------------------------------------------------------

TOKEN_PATTERN = re.compile(r"\s*([A-Za-z_][A-Za-z_0-9]*|\d+|[()]|,)")
PREFIX_FUNCTIONS = {"AND": 2, "OR": 2, "XOR": 2, "NOT": 1, "MUX": 3}


def tokenize_clause(text: str) -> List[str]:
    tokens: List[str] = []
    position = 0
    while position < len(text):
        match = TOKEN_PATTERN.match(text, position)
        if not match:
            raise ValueError(f"cannot tokenize clause at offset {position}: {text[position:position+12]!r}")
        tokens.append(match.group(1))
        position = match.end()
    if not tokens:
        raise ValueError("empty clause")
    return tokens


class ClauseParser:
    """
    Recursive descent parser for the clause DSL of section 2 of the specification.

        clause    := or_expr [ 'MUX' or_expr ]          infix value MUX select -> select ? value : 0
        or_expr   := xor_expr ( 'OR'  xor_expr )*
        xor_expr  := and_expr ( 'XOR' and_expr )*
        and_expr  := not_expr ( 'AND' not_expr )*
        not_expr  := 'NOT' not_expr | primary
        primary   := VAR | 0 | 1 | '(' clause ')' | FUNC '(' argument_list ')'
    """

    def __init__(self, tokens: Sequence[str], variable_bits: Dict[str, int], input_bits: int):
        self.tokens = list(tokens)
        self.position = 0
        self.variable_bits = variable_bits
        self.input_bits = input_bits

    def peek(self) -> str | None:
        return self.tokens[self.position] if self.position < len(self.tokens) else None

    def take(self) -> str:
        token = self.peek()
        if token is None:
            raise ValueError("clause ends unexpectedly")
        self.position += 1
        return token

    def parse_clause(self) -> Tuple:
        value = self.parse_or()
        if self.peek() == "MUX":
            self.take()
            select = self.parse_or()
            return ("mux", select, value, ("const", 0))
        return value

    def parse_or(self) -> Tuple:
        node = self.parse_xor()
        while self.peek() == "OR":
            self.take()
            node = ("or", node, self.parse_xor())
        return node

    def parse_xor(self) -> Tuple:
        node = self.parse_and()
        while self.peek() == "XOR":
            self.take()
            node = ("xor", node, self.parse_and())
        return node

    def parse_and(self) -> Tuple:
        node = self.parse_not()
        while self.peek() == "AND":
            self.take()
            node = ("and", node, self.parse_not())
        return node

    def parse_not(self) -> Tuple:
        if self.peek() == "NOT":
            self.take()
            return ("not", self.parse_not())
        return self.parse_primary()

    def parse_primary(self) -> Tuple:
        token = self.take()
        if token == "(":
            node = self.parse_clause()
            if self.take() != ")":
                raise ValueError("missing closing parenthesis")
            return node
        if token.isdigit():
            if token not in ("0", "1"):
                raise ValueError(f"only the constants 0 and 1 are allowed, got {token}")
            return ("const", int(token))
        upper = token.upper()
        if upper in PREFIX_FUNCTIONS:
            if self.take() != "(":
                raise ValueError(f"{upper} must be called with parentheses")
            arguments = [self.parse_clause()]
            while self.peek() == ",":
                self.take()
                arguments.append(self.parse_clause())
            if self.take() != ")":
                raise ValueError(f"missing closing parenthesis of {upper}")
            if upper == "MUX":
                if len(arguments) != 3:
                    raise ValueError("prefix MUX takes exactly (select, when-set, when-clear)")
                return ("mux",) + tuple(arguments)
            minimum = PREFIX_FUNCTIONS[upper]
            if len(arguments) < minimum:
                raise ValueError(f"{upper} takes at least {minimum} operands")
            node = (upper.lower(),) + tuple(arguments)
            return node
        if token in self.variable_bits:
            bit = self.variable_bits[token]
            if not 0 <= bit < self.input_bits:
                raise ValueError(f"variable {token} maps to bit {bit}, outside the input width")
            return ("var", token)
        raise ValueError(f"unknown token or variable {token!r}")

    def finish(self, node: Tuple) -> Tuple:
        if self.position != len(self.tokens):
            raise ValueError(f"trailing tokens after clause: {self.tokens[self.position:]}")
        return node


def clause_depth(node: Tuple) -> int:
    if node[0] in ("var", "const"):
        return 0
    return 1 + max(clause_depth(child) for child in node[1:])


def eval_parsed_clause(node: Tuple, bits: int, variable_bits: Dict[str, int]) -> int:
    if node[0] == "var":
        return (bits >> variable_bits[node[1]]) & 1
    if node[0] == "const":
        return node[1]
    if node[0] == "not":
        return 1 - eval_parsed_clause(node[1], bits, variable_bits)
    if node[0] == "mux":
        select = eval_parsed_clause(node[1], bits, variable_bits)
        chosen = node[2] if select else node[3]
        return eval_parsed_clause(chosen, bits, variable_bits)
    values = [eval_parsed_clause(child, bits, variable_bits) for child in node[1:]]
    if node[0] == "and":
        return 1 if all(values) else 0
    if node[0] == "or":
        return 1 if any(values) else 0
    if node[0] == "xor":
        result = 0
        for value in values:
            result ^= value
        return result
    raise ValueError(f"unknown clause operator {node[0]}")


def build_smt_netlist(smt_artifact: Dict[str, object]) -> Dict[str, object]:
    """Parse every clause and emit a latch-free assign netlist, one wire per boolean node."""
    input_bits = int(smt_artifact.get("input_bits", TOP_SMT_IN_BITS))
    lanes = int(smt_artifact.get("result_lanes", TOP_SMT_LANES))
    raw_map = smt_artifact.get("variable_bits", {})
    if not isinstance(raw_map, dict) or not raw_map:
        raise ValueError("variable_bits must be a non-empty object mapping letters to bit indexes")
    variable_bits = {name: int(bit) for name, bit in raw_map.items()}
    for name, bit in variable_bits.items():
        if not 0 <= bit < input_bits:
            raise ValueError(f"variable {name} maps to bit {bit}, outside the {input_bits}-bit input")
    clauses = smt_artifact.get("clauses", [])
    if not clauses:
        raise ValueError("no clauses declared")
    if len(clauses) > lanes:
        raise ValueError(f"{len(clauses)} clauses do not fit {lanes} result lanes")

    ids = [int(clause["id"]) for clause in clauses]
    if len(set(ids)) != len(ids):
        raise ValueError("clause ids are not unique")
    if any(not 0 <= clause_id < lanes for clause_id in ids):
        raise ValueError(f"clause ids must be in [0, {lanes})")

    lines: List[str] = []
    reports: List[Dict[str, object]] = []
    lines.append(f"  // Input bit map of the clause variables, bit 0 is the least significant bit.")
    for name in sorted(variable_bits, key=lambda key: variable_bits[key]):
        lines.append(f"  wire logic v_{name.lower()} = in_bits[{variable_bits[name]}];")
    lines.append("")

    max_depth = 0
    for clause in sorted(clauses, key=lambda item: int(item["id"])):
        clause_id = int(clause["id"])
        text = str(clause["expr"])
        parser = ClauseParser(tokenize_clause(text), variable_bits, input_bits)
        node = parser.finish(parser.parse_clause())
        depth = clause_depth(node)
        max_depth = max(max_depth, depth)
        wires: Dict[Tuple, str] = {}
        counter = 0
        lines.append(f"  // Clause {clause_id}: {text}")

        def emit(subtree: Tuple) -> str:
            nonlocal counter
            if subtree[0] == "var":
                return f"v_{subtree[1].lower()}"
            if subtree[0] == "const":
                return f"1'b{subtree[1]}"
            if subtree in wires:
                return wires[subtree]
            name = f"cl{clause_id}_n{counter}"
            counter += 1
            if subtree[0] == "not":
                operand = emit(subtree[1])
                lines.append(f"  wire logic {name} = ~{operand};")
            elif subtree[0] == "mux":
                select = emit(subtree[1])
                when_set = emit(subtree[2])
                when_clear = emit(subtree[3])
                lines.append(f"  wire logic {name} = {select} ? {when_set} : {when_clear};")
            else:
                operator = {"and": "&", "or": "|", "xor": "^"}[subtree[0]]
                operands = [emit(child) for child in subtree[1:]]
                expression = operands[0]
                for operand in operands[1:]:
                    expression = f"({expression} {operator} {operand})"
                lines.append(f"  wire logic {name} = {expression};")
            wires[subtree] = name
            return name

        result_wire = emit(node)
        lines.append(f"  assign clause_results[{clause_id}] = {result_wire};")
        lines.append("")
        reports.append(
            {
                "id": clause_id,
                "expr": text,
                "nodes": counter,
                "logic_depth": depth,
                "truth_table": [eval_parsed_clause(node, bits, variable_bits) for bits in range(256)],
            }
        )

    filled = set(ids)
    unused = [lane for lane in range(lanes) if lane not in filled]
    for lane in unused:
        lines.append(f"  assign clause_results[{lane}] = 1'b0;  // no clause mapped to this lane")

    return {
        "input_bits": input_bits,
        "lanes": lanes,
        "variable_bits_map": variable_bits,
        "body": "\n".join(lines),
        "clauses": reports,
        "max_logic_depth": max_depth,
        "unused_lanes": unused,
    }


