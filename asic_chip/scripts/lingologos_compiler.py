GOLDEN_COLUMNS = [
    "in0",
    "in1",
    "in2",
    "in3",
    "gf_sym",
    "smt_bits",
    "exp_out0",
    "exp_out1",
    "exp_out2",
    "exp_out3",
    "exp_gf_state",
    "exp_smt",
]


def to_signed_hex(value: int, bits: int) -> str:
    mask = (1 << bits) - 1
    return f"{value & mask:0{(bits + 3) // 4}X}"


def build_golden_vectors(
    mesh: Dict[str, object],
    gf_info: Dict[str, object],
    smt_info: Dict[str, object],
    vector_count: int,
    seed: int,
    smt_sweep: bool,
) -> Dict[str, object]:
    """
    Build the vector table both simulators consume. The generator is seeded, so the table is
    byte-identical run to run and the committed RTL can be checked against it.
    """
    matrix = mesh["matrix"]  # type: ignore[index]
    rows = int(mesh["rows"])  # type: ignore[index]
    cols = int(mesh["cols"])  # type: ignore[index]
    acc_bits = int(mesh["acc_bits"])  # type: ignore[index]
    variable_bits = smt_info["variable_bits_map"]  # type: ignore[index]
    lane_values = {clause["id"]: clause["truth_table"] for clause in smt_info["clauses"]}  # type: ignore[index]

    fixed_inputs: List[Tuple[int, ...]] = [
        (0, 0, 0, 0),
        (10, -5, 2, 100),
        (127, 127, 127, 127),
        (-128, -128, -128, -128),
        (-128, 127, -128, 127),
        (1, 1, 1, 1),
    ]
    fixed_symbols = [0x00, 0x41, 0x28, 0x28, 0x29, 0x5B]
    fixed_smt = [0x00, 0x5A, 0xFF, 0x0F, 0xA5, 0x3C]

    rng = random.Random(seed)
    vectors: List[Tuple[Tuple[int, ...], int, int]] = []
    for index in range(len(fixed_inputs)):
        vectors.append((fixed_inputs[index], fixed_symbols[index], fixed_smt[index]))
    # Three bracket words applied to the automaton without a gap between their rows. Every
    # multiplier is invertible, so the state after a word is the state before it times the
    # product of its letters: a word is "balanced" exactly when the state comes back to the
    # value it started from. The crossed word comes back too, which is the documented
    # limitation of a commutative image and not a bug in the generated table.
    bracket_words = [
        ("balanced_round_and_square", [0x28, 0x29, 0x5B, 0x5D]),
        ("crossed_round_open_square_close", [0x28, 0x5D]),
        ("three_unmatched_opens", [0x28, 0x28, 0x28]),
    ]
    word_reports: List[Dict[str, object]] = []
    chain_state = int(gf_info["initial"])  # type: ignore[arg-type]
    for symbol in fixed_symbols:
        chain_state = gf_apply(gf_info, chain_state, symbol)
    for name, word in bracket_words:
        state_before = chain_state
        for symbol in word:
            chain_state = gf_apply(gf_info, chain_state, symbol)
            vectors.append(((0, 0, 0, 0), symbol, 0x00))
        word_reports.append(
            {
                "name": name,
                "symbols": [f"0x{symbol:02X}" for symbol in word],
                "state_before": f"0x{state_before:02X}",
                "state_after": f"0x{chain_state:02X}",
                "returns_to_start": chain_state == state_before,
            }
        )
    while len(vectors) < vector_count:
        vectors.append(
            (
                tuple(rng.randrange(-(1 << (TOP_IN_BITS - 1)), 1 << (TOP_IN_BITS - 1)) for _ in range(cols)),
                rng.randrange(256),
                rng.randrange(256),
            )
        )
    if smt_sweep:
        for sweep in range(256):
            vectors.append(
                (
                    tuple(rng.randrange(-(1 << (TOP_IN_BITS - 1)), 1 << (TOP_IN_BITS - 1)) for _ in range(cols)),
                    0x29,
                    sweep,
                )
            )

    state = int(gf_info["initial"])  # type: ignore[arg-type]
    rows_out: List[List[str]] = []
    for inputs, symbol, smt_bits in vectors:
        for value in inputs:
            if not -(1 << (TOP_IN_BITS - 1)) <= value < (1 << (TOP_IN_BITS - 1)):
                raise ValueError(f"input {value} does not fit the signed INT{TOP_IN_BITS} pad")
        sums = [mesh_row_value(matrix, row, inputs) for row in range(rows)]
        if any(abs(total) > (1 << (acc_bits - 1)) - 1 for total in sums):
            raise ValueError(f"row sum of {inputs} does not fit the signed {acc_bits}-bit accumulator")
        state = gf_apply(gf_info, state, symbol)
        clause_word = 0
        for clause_id, table in lane_values.items():
            bit = table[smt_bits]
            clause_word |= bit << clause_id
        record = [to_signed_hex(value, TOP_IN_BITS) for value in inputs]
        record.append(f"{symbol:02X}")
        record.append(f"{smt_bits:02X}")
        record.extend(to_signed_hex(total, acc_bits) for total in sums)
        record.append(f"{state:02X}")
        record.append(f"{clause_word:X}")
        rows_out.append(record)

    header = [
        "// LingoLOGOS golden vectors, generated by asic_chip/scripts/lingologos_compiler.py.",
        "// Schema lingologos-golden-1. Hex, two's complement for the signed mesh fields.",
        "// Columns: " + " ".join(GOLDEN_COLUMNS),
        "// The GF automaton is a chain: exp_gf_state of a row is the state after applying",
        "// that row symbol to the state left by the previous row, starting from initial_state.",
        "// exp_out* and exp_gf_state are sampled one clock edge after the row is driven;",
        "// exp_smt is combinational and is valid while the row inputs are driven.",
    ]
    body = [" ".join(record) for record in rows_out]
    return {
        "header": header,
        "text": "\n".join(header + body) + "\n",
        "rows": rows_out,
        "row_count": len(rows_out),
        "final_state": state,
        "distinct_smt_bytes": len({record[5] for record in rows_out}),
        "word_reports": word_reports,
    }


