def render_weight_module(mesh: Dict[str, object]) -> str:
    rows = int(mesh["rows"])  # type: ignore[int]
    cols = int(mesh["cols"])  # type: ignore[int]
    acc_bits = int(mesh["acc_bits"])  # type: ignore[int]
    lines = [
        SV_GENERATED_BANNER,
        "// Source artifact: asic_chip/artifacts/model_weights.json, schema lingologos-weight-mesh-1.",
        "// Combinatorial weight mesh: each constant multiply is a shift-add tree fixed in netlist",
        "// form, so there is no multiplier cell and no memory in the datapath.",
        "// Pad-level flat ports, as the datasheet pin table and the C++ harness both drive",
        "// in_vector_0..3 and read out_vector_0..3 one signal per pin.",
        "module weight_rom_mesh (",
    ]
    declarations: List[str] = []
    for col in range(cols):
        declarations.append(f"    input  logic signed [{TOP_IN_BITS - 1}:0] in_vec_{col}")
    for row in range(rows):
        declarations.append(f"    output logic signed [{acc_bits - 1}:0] out_vec_{row}")
    lines.append(",\n".join(declarations))
    lines.append(");")
    lines.append("")
    lines.append(mesh["body"])  # type: ignore[index]
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def render_gf_module(gf_info: Dict[str, object]) -> str:
    symbol_note = ", ".join(
        f"{symbol['byte']:#04x} -> x {symbol['multiplier']:#04x}" for symbol in gf_info["symbols"]  # type: ignore[index]
    )
    lines = [
        SV_GENERATED_BANNER,
        "// Source artifact: asic_chip/artifacts/gf_rules.json, schema lingologos-gf-automaton-1.",
        f"// Field GF(2^8) modulo 0x{int(gf_info['poly']):03X}, initial state 0x{int(gf_info['initial']):02X}.",  # type: ignore[arg-type]
        f"// {int(gf_info['state_count'])} reachable states, {len(gf_info['transitions'])} defined transitions, ",  # type: ignore[arg-type]
        f"// inside the declared budget of {int(gf_info['budget'])}.  (state, symbol) pairs are unique.",  # type: ignore[arg-type]
        f"// Symbol multipliers: {symbol_note}. Any other symbol falls in the default arm and",
        "// returns the initial state, so the automaton is fully defined and latch-free.",
        "module gf_automaton_1cycle (",
        "    input  logic [7:0] current_state,",
        "    input  logic [7:0] symbol_in,",
        "    output logic [7:0] next_state",
        ");",
        "",
        gf_info["body"],  # type: ignore[index]
        "endmodule",
    ]
    return "\n".join(lines) + "\n"


def render_smt_module(smt_info: Dict[str, object]) -> str:
    depth_note = ", ".join(
        f"clause {clause['id']}: {clause['nodes']} nodes, depth {clause['logic_depth']}"
        for clause in smt_info["clauses"]  # type: ignore[union-attr]
    )
    lines = [
        SV_GENERATED_BANNER,
        "// Source artifact: asic_chip/artifacts/smt_constraints.json, schema lingologos-smt-clauses-1.",
        "// Pure assign netlist: no always block, no latch, one wire per boolean node.",
        f"// Deepest cone: {int(smt_info['max_logic_depth'])} levels. ({depth_note})",
        "module smt_evaluator (",
        f"    input  logic [{int(smt_info['input_bits']) - 1}:0] in_bits,",  # type: ignore[arg-type]
        f"    output logic [{int(smt_info['lanes']) - 1}:0] clause_results",  # type: ignore[arg-type]
        ");",
        "",
        smt_info["body"],  # type: ignore[index]
        "endmodule",
    ]
    return "\n".join(lines) + "\n"


