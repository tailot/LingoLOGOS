# H5: core self-test stimulus and expected coprocessor readbacks
# ---------------------------------------------------------------------------

# The stimulus below is frozen while the RV32E self-test runs, so every coprocessor
# readback the firmware deposits in a register is predictable. The datasheet worked
# example uses the same four input values, which keeps one set of numbers across the
# documents and the simulators.
SELF_TEST_STIMULUS = {
    "in_vector": [10, -5, 2, 100],
    "gf_symbol_in": 0x00,
    "smt_in_bits": 0x5A,
    # The firmware properties below describe the listing in
    # rtl/core/rv32e_core.sv: the mesh row the readback instruction selects, the
    # symbol it feeds the automaton, and how many coprocessor datapath instructions
    # run before the status instruction. tests/test_asic_compiler.py re-derives them
    # by decoding the ROM words, so a firmware edit that changes one of them fails a
    # test instead of silently moving a constant.
    "mesh_row_index": 2,
    "gf_step_symbol": 0x28,
    "cop_ops_before_status": 3,
    "illegal_before_status": 1,
    "status_illegal_bit": 4,
}


def build_core_self_test(
    mesh: Dict[str, object],
    gf_info: Dict[str, object],
    smt_info: Dict[str, object],
) -> Dict[str, object]:
    """Freeze the self-test pads and predict every coprocessor readback."""
    matrix = mesh["matrix"]  # type: ignore[index]
    rows = int(mesh["rows"])  # type: ignore[arg-type]
    acc_bits = int(mesh["acc_bits"])  # type: ignore[arg-type]
    inputs = [int(value) for value in SELF_TEST_STIMULUS["in_vector"]]  # type: ignore[index]
    smt_bits = int(SELF_TEST_STIMULUS["smt_in_bits"])  # type: ignore[index]
    idle_symbol = int(SELF_TEST_STIMULUS["gf_symbol_in"])  # type: ignore[index]
    row_index = int(SELF_TEST_STIMULUS["mesh_row_index"])  # type: ignore[index]
    step_symbol = int(SELF_TEST_STIMULUS["gf_step_symbol"])  # type: ignore[index]
    cop_ops = int(SELF_TEST_STIMULUS["cop_ops_before_status"])  # type: ignore[index]
    illegal = int(SELF_TEST_STIMULUS["illegal_before_status"])  # type: ignore[index]
    illegal_bit = int(SELF_TEST_STIMULUS["status_illegal_bit"])  # type: ignore[index]

    if row_index not in range(rows):
        raise ValueError("self-test mesh row index is outside the mesh")
    for value in inputs:
        if not -(1 << (TOP_IN_BITS - 1)) <= value < (1 << (TOP_IN_BITS - 1)):
            raise ValueError(f"self-test input {value} does not fit the signed INT{TOP_IN_BITS} pad")

    sums = [mesh_row_value(matrix, row, inputs) for row in range(rows)]
    for total in sums:
        if abs(total) > (1 << (acc_bits - 1)) - 1:
            raise ValueError(f"self-test row sum {total} does not fit the signed {acc_bits}-bit field")

    initial = int(gf_info["initial"])  # type: ignore[arg-type]
    state_after_step = gf_apply(gf_info, initial, step_symbol)
    state_after_idle = gf_apply(gf_info, state_after_step, idle_symbol)

    smt_word = 0
    for clause in smt_info["clauses"]:  # type: ignore[index]
        smt_word |= clause["truth_table"][smt_bits] << int(clause["id"])

    status_word = cop_ops + (illegal << illegal_bit)

    values = {
        "in_vector_0": to_signed_hex(inputs[0], TOP_IN_BITS),
        "in_vector_1": to_signed_hex(inputs[1], TOP_IN_BITS),
        "in_vector_2": to_signed_hex(inputs[2], TOP_IN_BITS),
        "in_vector_3": to_signed_hex(inputs[3], TOP_IN_BITS),
        "gf_symbol_in": f"{idle_symbol:02X}",
        "smt_in_bits": f"{smt_bits:02X}",
        "gf_step_symbol": f"{step_symbol:02X}",
        "mesh_row_index": f"{row_index:02X}",
        "exp_x8": to_signed_hex(smt_word, 32),
        "exp_x10": f"{state_after_step:02X}",
        "exp_x11": to_signed_hex(sums[row_index], 32),
        "exp_x13": to_signed_hex(status_word, 32),
        # The status word carries the counter as it stood when the status request was
        # read, that is without the status request itself. The counter register keeps
        # counting, so a harness that looks at it after the run sees one more.
        "exp_cop_count": f"{cop_ops + 1:02X}",
        "exp_x15": to_signed_hex(0, 32),
        "exp_core_pass": "1",
        "exp_core_illegal_seen": "1",
        "exp_gf_state_final": f"{state_after_idle:02X}",
    }
    header = [
        "// LingoLOGOS core self-test, generated by asic_chip/scripts/lingologos_compiler.py.",
        "// Schema lingologos-selftest-1. One key and one hex value per line, // starts a comment.",
        "// The pad columns hold while the RV32E self-test runs, so the readbacks below are",
        "// predictable: x8 is the SMT lane word, x10 the automaton state produced by the step",
        "// instruction, x11 the selected mesh row, x13 the coprocessor status word.",
        "// x15 is the firmware error accumulator, zero means every instruction check passed.",
        "// exp_cop_count is the coprocessor request counter after the status request that",
        "// filled x13 has itself been counted, so it is one more than the counter field of",
        "// x13: the status word is read combinationally, before that request increments.",
    ]
    body = [f"{key} = {value}" for key, value in values.items()]
    return {
        "text": "\n".join(header + body) + "\n",
        "values": values,
        "row_sums": sums,
        "smt_word": smt_word,
        "state_after_step": state_after_step,
        "state_after_idle": state_after_idle,
        "status_word": status_word,
    }


