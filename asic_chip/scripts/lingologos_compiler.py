def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def load_artifacts(artifact_dir: Path) -> Dict[str, object]:
    names = ["model_weights.json", "gf_rules.json", "smt_constraints.json"]
    loaded: Dict[str, object] = {}
    for name in names:
        path = artifact_dir / name
        if not path.is_file():
            raise FileNotFoundError(f"missing artifact {path}")
        loaded[name] = json.loads(path.read_text(encoding="utf-8"))
    loaded["_digests"] = {name: sha256_of(artifact_dir / name) for name in names}
    return loaded


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Compile the LingoLOGOS AI artifacts into SystemVerilog RTL"
    )
    parser.add_argument("--artifacts-dir", default=str(ARTIFACT_DIR), help="folder holding the JSON artifacts")
    parser.add_argument("--out-dir", default=str(OUTPUT_DIR), help="folder receiving the generated RTL")
    parser.add_argument(
        "--sim-dir",
        default=str(SIM_DIR),
        help="folder receiving the golden vector and self-test memory files",
    )
    parser.add_argument("--vectors", type=int, default=48, help="number of generated golden vectors")
    parser.add_argument("--seed", type=int, default=42, help="seed of the golden vector table")
    parser.add_argument(
        "--smt-sweep",
        dest="smt_sweep",
        action="store_true",
        default=True,
        help="append one vector for every one of the 256 SMT input bytes",
    )
    parser.add_argument(
        "--no-smt-sweep",
        dest="smt_sweep",
        action="store_false",
        help="skip the exhaustive SMT input sweep",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and compare with the committed files, write nothing",
    )
    parser.add_argument("--lenient", action="store_true", help="do not exit non-zero when a gate fails")
    return parser


def main(argv: List[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    artifact_dir = Path(args.artifacts_dir)
    if not artifact_dir.is_absolute():
        artifact_dir = repo_root / artifact_dir
    out_dir = Path(args.out_dir)
    if not out_dir.is_absolute():
        out_dir = repo_root / out_dir
    sim_dir = Path(args.sim_dir)
    if not sim_dir.is_absolute():
        sim_dir = repo_root / sim_dir

    artifacts = load_artifacts(artifact_dir)
    weights_artifact = artifacts["model_weights.json"]
    matrix = weights_artifact["weight_matrix"]["values"]
    precision = weights_artifact["weight_matrix"].get("precision", "INT8")
    acc_bits = int(weights_artifact["weight_matrix"].get("accumulator_bits", 20))

    gate = {}
    numbers: Dict[str, object] = {}

    # ---- H1 weight mesh
    try:
        if precision != "INT8":
            raise ValueError(f"precision {precision} is not supported by the INT8 pads")
        if len(matrix) != TOP_MESH_ROWS or any(len(row) != TOP_MESH_COLS for row in matrix):
            raise ValueError(
                f"the datasheet pin table fixes a {TOP_MESH_ROWS}x{TOP_MESH_COLS} mesh, "
                f"the artifact declares {len(matrix)}x{len(matrix[0]) if matrix else 0}"
            )
        for row in matrix:
            for weight in row:
                if not -128 <= int(weight) <= 127:
                    raise ValueError(f"weight {weight} is outside INT8")
        mesh = build_weight_mesh([
            [int(value) for value in row] for row in matrix
        ], acc_bits, TOP_IN_BITS)
        h1 = bool(mesh["shift_width_ok"]) and all(
            report["fits_accumulator"] for report in mesh["rows_report"]
        )
        numbers["H1_mesh"] = {
            "dims": [mesh["rows"], mesh["cols"]],
            "accumulator_bits": acc_bits,
            "accumulator_limit": mesh["accumulator_limit"],
            "max_shift": mesh["max_shift"],
            "worst_partial_sum_bound": mesh["worst_partial_bound"],
            "headroom_ratio": round(mesh["accumulator_limit"] / max(1, mesh["worst_partial_bound"]), 2),
        }
    except (ValueError, KeyError, TypeError) as error:
        gate["H1_weight_mesh_fits"] = False
        print(f"[H1] weight mesh rejected: {error}")
        raise SystemExit(1 if not args.lenient else 0)
    gate["H1_weight_mesh_fits"] = h1

    # ---- H2 GF automaton
    try:
        gf_info = build_gf_transitions(artifacts["gf_rules.json"])
        gate["H2_gf_table_closed"] = True
        numbers["H2_gf"] = {
            "polynomial": f"0x{gf_info['poly']:03X}",
            "irreducible": True,
            "reachable_states": gf_info["state_count"],
            "state_budget": gf_info["budget"],
            "defined_transitions": len(gf_info["transitions"]),
            "symbol_orders": gf_info["symbol_orders"],
        }
    except ValueError as error:
        gate["H2_gf_table_closed"] = False
        print(f"[H2] GF automaton rejected: {error}")
        gf_info = {}

    # ---- H3 SMT netlist
    try:
        smt_info = build_smt_netlist(artifacts["smt_constraints.json"])
        latch_free = "always" not in smt_info["body"]
        gate["H3_smt_netlist_latch_free"] = latch_free
        numbers["H3_smt"] = {
            "clauses": len(smt_info["clauses"]),
            "result_lanes": smt_info["lanes"],
            "unused_lanes": smt_info["unused_lanes"],
            "max_logic_depth": smt_info["max_logic_depth"],
            "clause_nodes": {str(clause["id"]): clause["nodes"] for clause in smt_info["clauses"]},
        }
    except ValueError as error:
        gate["H3_smt_netlist_latch_free"] = False
        print(f"[H3] SMT clauses rejected: {error}")
        smt_info = {}

    if not all(gate.values()):
        print("Final gates:", json.dumps(gate, indent=2))
        print("FINAL VERDICT: FAIL")
        return 0 if args.lenient else 1

    # ---- H4 golden vectors
    vectors = build_golden_vectors(
        mesh, gf_info, smt_info, args.vectors, args.seed, args.smt_sweep
    )
    gate["H4_golden_vectors_in_range"] = True
    numbers["H4_vectors"] = {
        "rows": vectors["row_count"],
        "seed": args.seed,
        "distinct_smt_bytes": vectors["distinct_smt_bytes"],
        "final_gf_state": f"0x{vectors['final_state']:02X}",
        "bracket_words": vectors["word_reports"],
    }

    # ---- H5 core self-test
    try:
        self_test = build_core_self_test(mesh, gf_info, smt_info)
        gate["H5_core_self_test_consistent"] = True
    except (ValueError, KeyError, TypeError, IndexError) as error:
        gate["H5_core_self_test_consistent"] = False
        print(f"[H5] core self-test rejected: {error}")
        numbers["H5_selftest"] = {}
        print("Final gates:", json.dumps(gate, indent=2))
        print("FINAL VERDICT: FAIL")
        return 0 if args.lenient else 1
    numbers["H5_selftest"] = {
        "in_vector": SELF_TEST_STIMULUS["in_vector"],
        "row_sums": self_test["row_sums"],
        "smt_readback": f"0x{self_test['smt_word']:02X}",
        "gf_state_after_step": f"0x{self_test['state_after_step']:02X}",
        "gf_state_after_idle": f"0x{self_test['state_after_idle']:02X}",
        "status_word": f"0x{self_test['status_word']:02X}",
    }

    rendered = {
        "weight_rom_mesh.sv": render_weight_module(mesh),
        "gf_automaton_1cycle.sv": render_gf_module(gf_info),
        "smt_evaluator.sv": render_smt_module(smt_info),
    }
    golden_text = vectors["text"]
    selftest_text = self_test["text"]

    mismatches: List[str] = []
    for name, text in rendered.items():
        target = out_dir / name
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                mismatches.append(name)
    if args.check:
        golden_target = sim_dir / "golden_vectors.mem"
        if not golden_target.is_file() or golden_target.read_text(encoding="utf-8") != golden_text:
            mismatches.append("sim/golden_vectors.mem")
        selftest_target = sim_dir / "core_self_test.mem"
        if not selftest_target.is_file() or selftest_target.read_text(encoding="utf-8") != selftest_text:
            mismatches.append("sim/core_self_test.mem")
        gate["RTL_matches_artifacts"] = not mismatches
        if mismatches:
            print("Stale generated files:", ", ".join(mismatches))
    else:
        out_dir.mkdir(parents=True, exist_ok=True)
        sim_dir.mkdir(parents=True, exist_ok=True)
        for name, text in rendered.items():
            (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
        (sim_dir / "golden_vectors.mem").write_text(golden_text, encoding="utf-8", newline="\n")
        (sim_dir / "core_self_test.mem").write_text(selftest_text, encoding="utf-8", newline="\n")
        manifest = {
            "schema": "lingologos-manifest-1",
            "generator": "asic_chip/scripts/lingologos_compiler.py",
            "artifact_digests": artifacts["_digests"],
            "output_digests": {
                name: hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
                for name, text in rendered.items()
            },
            "golden_vectors_digest": hashlib.sha256(golden_text.encode("utf-8")).hexdigest()[:16],
            "self_test_digest": hashlib.sha256(selftest_text.encode("utf-8")).hexdigest()[:16],
            "measurements": numbers,
            "gates": gate,
        }
        (out_dir / "MANIFEST.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8", newline="\n"
        )

    for key, value in numbers.items():
        print(f"{key}: {json.dumps(value)}")
    print("Final gates:", json.dumps(gate, indent=2))
    verdict = "PASS" if all(gate.values()) else "FAIL"
    print("FINAL VERDICT:", verdict)
    if verdict == "FAIL" and not args.lenient:
        return 1
    return 0


