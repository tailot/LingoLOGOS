# H1: weight mesh
# ---------------------------------------------------------------------------

def naf_decompose(magnitude: int) -> List[Tuple[int, int]]:
    """
    Non-adjacent form of a positive magnitude as a list of (shift, sign) digits, so a
    constant multiply becomes the fewest possible shift-add steps in the netlist.
    """
    if magnitude <= 0:
        raise ValueError("magnitude must be positive")
    digits: List[Tuple[int, int]] = []
    value = magnitude
    position = 0
    while value > 0:
        if value & 1:
            digit = 2 - (value % 4)
            digits.append((position, 1 if digit > 0 else -1))
            value = (value - digit) >> 1
        else:
            value >>= 1
        position += 1
    reconstructed = sum(sign * (1 << shift) for shift, sign in digits)
    if reconstructed != magnitude:
        raise AssertionError(f"decomposition of {magnitude} reconstructs {reconstructed}")
    if len(digits) > magnitude.bit_count() + 1:
        raise AssertionError(f"non-adjacent form of {magnitude} is not compact")
    return digits


def naf_weight_sum(digits: Sequence[Tuple[int, int]]) -> int:
    """Sum of the magnitudes of the digits, an upper bound on the term for any input."""
    return sum(1 << shift for shift, _ in digits)


def render_shift(shift: int, wire: str) -> str:
    return wire if shift == 0 else f"({wire} <<< {shift})"


def build_weight_mesh(matrix: List[List[int]], acc_bits: int, in_bits: int) -> Dict[str, object]:
    """
    Emit the netlist of the combinatorial weight mesh. Every constant is expanded into its
    non-adjacent form so the synthesis tool sees shift-add trees instead of a multiplier, and
    every partial sum is bounded so the accumulator width is provable rather than assumed.
    """
    rows = len(matrix)
    cols = len(matrix[0]) if rows else 0
    if any(len(row) != cols for row in matrix):
        raise ValueError("weight matrix is not rectangular")

    max_abs_input = 1 << (in_bits - 1)  # two's complement magnitude of the most negative value
    acc_limit = (1 << (acc_bits - 1)) - 1
    lines: List[str] = []
    row_reports: List[Dict[str, object]] = []
    max_shift = 0
    worst_prefix_bound = 0

    lines.append(
        f"  // Sign-extended input copies: one {acc_bits}-bit signed wire per mesh column."
    )
    lines.append(
        "  // The right hand side of these wires is declared signed, so the rules of the"
    )
    lines.append(
        "  // language extend it into the accumulator width with copies of its sign bit. The"
    )
    lines.append(
        "  // pragma pair states that this widening is intended, which keeps the lint report"
    )
    lines.append("  // free of a false positive without hiding anything from the reader.")
    lines.append("  /* verilator lint_off WIDTHEXPAND */")
    for col in range(cols):
        lines.append(
            f"  wire logic signed [{acc_bits - 1}:0] c{col} = $signed(in_vec_{col});"
        )
    lines.append("  /* verilator lint_on WIDTHEXPAND */")
    lines.append("")

    for row in range(rows):
        term_wires: List[str] = []
        prefix_bound = 0
        lines.append(
            "  // Row "
            + str(row)
            + ": Y_"
            + str(row)
            + " = "
            + " + ".join(f"{matrix[row][col]} * X_{col}" for col in range(cols))
        )
        for col in range(cols):
            weight = matrix[row][col]
            if weight == 0:
                lines.append(f"  // W[{row}][{col}] = 0: no adder, the column wire is unused here.")
                continue
            digits = naf_decompose(abs(weight))
            signed_digits = [
                (shift, sign if weight > 0 else -sign) for shift, sign in digits
            ]
            max_shift = max(max_shift, max(shift for shift, _ in signed_digits))
            parts: List[str] = []
            for shift, sign in signed_digits:
                rendered = render_shift(shift, f"c{col}")
                parts.append(rendered if sign > 0 else f"(-{rendered})")
            expression = parts[0]
            for part in parts[1:]:
                if part.startswith("(-"):
                    expression = f"{expression} - {part[2:-1]}"
                else:
                    expression = f"{expression} + {part}"
            wire_name = f"r{row}_c{col}"
            decomposition = " ".join(
                ("+" if sign > 0 else "-") + f"2^{shift}" for shift, sign in signed_digits
            )
            lines.append(
                f"  // W[{row}][{col}] = {weight} = {decomposition}"
                f"  ({len(signed_digits)} adder stages, bound {naf_weight_sum(digits)} * |X_{col}|)"
            )
            lines.append(f"  wire logic signed [{acc_bits - 1}:0] {wire_name} = {expression};")
            term_wires.append(wire_name)
            prefix_bound += naf_weight_sum(digits) * max_abs_input
            worst_prefix_bound = max(worst_prefix_bound, prefix_bound)

        if term_wires:
            sum_expression = term_wires[0]
            for wire in term_wires[1:]:
                sum_expression = f"({sum_expression} + {wire})"
        else:
            sum_expression = f"{acc_bits}'sd0"
            prefix_bound = 0
        lines.append(f"  assign out_vec_{row} = {sum_expression};")
        lines.append("")
        row_reports.append(
            {
                "row": row,
                "active_terms": len(term_wires),
                "adder_stages": sum(
                    len(naf_decompose(abs(w))) for w in matrix[row] if w != 0
                ),
                "partial_sum_bound": prefix_bound,
                "fits_accumulator": prefix_bound <= acc_limit,
            }
        )

    return {
        "matrix": matrix,
        "rows": rows,
        "cols": cols,
        "acc_bits": acc_bits,
        "body": "\n".join(lines),
        "max_shift": max_shift,
        "shift_width_ok": in_bits + max_shift <= acc_bits,
        "worst_partial_bound": worst_prefix_bound,
        "accumulator_limit": acc_limit,
        "rows_report": row_reports,
    }


def mesh_row_value(matrix: Sequence[Sequence[int]], row: int, inputs: Sequence[int]) -> int:
    """Exact integer dot product, the reference the generated adder tree must reproduce."""
    return sum(weight * value for weight, value in zip(matrix[row], inputs))


