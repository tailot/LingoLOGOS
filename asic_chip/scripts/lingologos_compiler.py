#!/usr/bin/env python3
"""
RTL generator for the LingoLOGOS ASIC: reads the AI artifacts in JSON and compiles them
into SystemVerilog, adder-tree decomposition of the weight mesh included.

Compliant with sections 2, 3 and 4 of the LingoLOGOS ASIC specification.

Usage:
    python asic_chip/scripts/lingologos_compiler.py                 # generate RTL
    python asic_chip/scripts/lingologos_compiler.py --check         # compare, write nothing
    python asic_chip/scripts/lingologos_compiler.py --vectors 64 --seed 7 --no-smt-sweep

Acceptance gates:
    H1 weight mesh: rectangular INT8 matrix, non-adjacent-form adder decomposition, every
       partial sum of the emitted netlist provably inside the signed accumulator
    H2 GF automaton: irreducible field polynomial, invertible symbol multipliers, closed and
       duplicate-free transition table inside the declared state budget
    H3 SMT clauses: DSL parses, netlist is acyclic and latch-free, clauses fit the result lanes
    H4 golden vectors: every vector regenerates inside the declared widths and the table is
       deterministic across runs
    H5 core self-test: the frozen self-test pads stay inside the pads, and every
       coprocessor readback the firmware will see is predicted inside its field width
Exit code is non-zero when a gate fails, unless --lenient is passed.
"""

